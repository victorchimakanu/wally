import { custodyOf, devServerConfigured, protectsDisplayedFunds, splitPermitted, type Custody } from './custody.ts';
/**
 * Opens the WDK Bare worklet and hands back a keystore bound to it.
 *
 * ────────────────────────────────────────────────────────────────────────────────────────────
 *  UNVERIFIED ON A DEVICE, like wallet-keystore.ts. Written against the installed packages'
 *  source with lines noted; never executed, because a Bare worklet needs a development build
 *  on a real phone. The first person to run this should expect to debug it.
 * ────────────────────────────────────────────────────────────────────────────────────────────
 *
 * Verified against the installed source:
 *   new Worklet(); worklet.start(name, source); worklet.IPC; worklet.terminate()
 *     react-native-bare-kit/index.d.ts:21-37 — `start` accepts the source as a string
 *   new HRPC(ipc)        @tetherto/pear-wrk-wdk/index.js exports { HRPC }
 *   bundle               .wdk-bundle/wdk-worklet.bundle.js, generated by `npm run wdk:generate`
 *                        from wdk.config.cjs; `.wdk/index.d.ts` declares `export const bundle: string`
 *
 * The worklet is started once per app run and reused. Starting a second one would mean two
 * WDK instances holding the same keys, and the §28.3 nonce problem in miniature on a single
 * device.
 */
import { Worklet } from 'react-native-bare-kit';
import { HRPC } from '@tetherto/pear-wrk-wdk';
import { bundle } from '../../.wdk/index.js';
import { createWalletVault } from './wallet-vault.ts';
import { createKeystore, type Keystore, type WorkletRpc } from './wallet-keystore.ts';
import { loadSecureStorage } from './secure-storage.ts';
import { backendOrigin, backendHeaders } from './backend.ts';
import { Platform } from 'react-native';

export const keystoreAvailable = true;
export function keystoreUnavailableReason(): string { return ''; }

let shared: Keystore | null = null;

/**
 * The networks WDK boots with, as a JSON string.
 *
 * Everything points at the backend proxy rather than at a provider directly, for the same
 * reason throughout: the keys stay off the device. For the bundler and paymaster that matters
 * more than for the RPC — Pimlico puts its API key in the endpoint URL, so an app carrying it
 * hands anyone who unzips the APK a sponsorship budget to spend.
 *
 * **Gasless is Arbitrum only, and it is sponsorship rather than fees-in-USDT.** The README's
 * promise — "fees in USDT" — cannot be delivered on the chain this app actually runs on: no
 * USDT paymaster exists on Arbitrum Sepolia. Pimlico's supported tokens there are USDC, EURe,
 * ostUSDC and PIM; USDT appears only on Arbitrum One (verified against Pimlico's own
 * supported-token list, 5 Nov 2026). So on testnet Wally sponsors the gas, which keeps the
 * part of the promise that matters to a user — they never need to hold ETH — and leaves
 * fees-in-USDT as a mainnet change rather than a fiction.
 *
 * Ethereum gets no bundler or paymaster because it is a plain EOA (`@tetherto/wdk-wallet-evm`).
 * There is no user operation to sponsor.
 */
async function workletConfig(): Promise<string> {
  const origin = backendOrigin();
  if (!origin) {
    throw new Error('No Wally backend is configured, so the wallet has no chain to talk to. Set EXPO_PUBLIC_WALLY_PROXY_URL.');
  }

  /**
   * Ask whether gasless is switched on, and treat any failure as "no".
   *
   * Falling back to paying gas in native coins is the safe direction. A wallet that asks for
   * ETH is usable by someone who has ETH; a wallet configured for a paymaster that is not
   * there fails at the moment of signing, which is the worst place to find out.
   */
  let gasless: { available?: unknown; submitEnabled?: unknown } = {};
  try {
    const response = await fetch(`${origin}/v1/gasless`, { headers: { Accept: 'application/json', ...backendHeaders(origin) } });
    if (response.ok) gasless = (await response.json()) as typeof gasless;
  } catch { /* treated as unavailable */ }

  const arbitrum: Record<string, unknown> = { rpcUrl: `${origin}/v1/rpc/arbitrum` };
  if (gasless.available === true) {
    arbitrum['bundlerUrl'] = `${origin}/v1/bundler/arbitrum`;
    arbitrum['paymasterUrl'] = `${origin}/v1/paymaster/arbitrum`;
    // Sponsorship mode: Wally pays. `isSponsored` is what selects it over the ERC-20 token
    // mode, which needs a paymasterAddress and a token address that testnet does not have.
    arbitrum['isSponsored'] = true;
  }

  return JSON.stringify({
    networks: {
      arbitrum: { blockchain: 'arbitrum', config: arbitrum },
      ethereum: { blockchain: 'ethereum', config: { rpcUrl: `${origin}/v1/rpc/ethereum` } },
    },
  });
}

export async function getKeystore(): Promise<Keystore> {
  if (shared) return shared;
  const storage = await loadSecureStorage(Platform.OS);
  // No OS keystore means nowhere safe for the key. Refusing is the only honest answer:
  // storing it anywhere else would put key material in app storage, which ADR-001 forbids.
  if (!storage) throw new Error('This device has no secure keystore, so Wally cannot hold a wallet on it.');

  shared = createKeystore(createWalletVault(storage), {
    async connect() {
      const worklet = new Worklet();
      // The filename is a label inside the worklet, not a path on disk; the source is the
      // generated bundle string.
      worklet.start('/wally-wallet.bundle.js', bundle);
      // Cast through unknown deliberately. HRPC's declared buffer parameters are `Buffer`,
      // and TypeScript treats Uint8Array as the wider type, so the two do not overlap
      // nominally. They do at runtime: the HRPC wire format encodes a buffer field through
      // compact-encoding's uint8array codec, and React Native has no Buffer to pass anyway.
      // WorkletRpc is the narrower surface Wally actually uses.
      const rpc = new HRPC(worklet.IPC) as unknown as WorkletRpc;
      return {
        rpc,
        close() { worklet.terminate(); },
      };
    },
    config: workletConfig,
  });
  return shared;
}

/**
 * `custody` travels with `backedUpAt` on purpose. Read alone, that timestamp says "this user
 * wrote their phrase down" and invites the conclusion "so their money is safe" — which is false
 * whenever the money on screen belongs to the dev wallet server rather than to this phone.
 * Carrying custody here means no caller can have one without the other.
 */
export type WalletStatus =
  | { available: false }
  | { available: true; exists: boolean; backedUpAt: number; custody: Custody; protectsDisplayedFunds: boolean };

/**
 * What this device holds, read from the vault alone.
 *
 * Deliberately does not start the worklet. Settings opens this on every visit, and spinning up
 * a Bare worklet — and with it a WDK instance holding keys — to answer "is there a wallet" and
 * "was it backed up" would be a cost and an exposure for no reason.
 */
export async function walletStatus(): Promise<WalletStatus> {
  const storage = await loadSecureStorage(Platform.OS);
  if (!storage) return { available: false };
  const record = await createWalletVault(storage).read();
  const custody = custodyOf({ keystoreWallet: record !== null, devServerConfigured, splitPermitted });
  return {
    available: true,
    exists: record !== null,
    backedUpAt: record?.backedUpAt ?? 0,
    custody,
    protectsDisplayedFunds: protectsDisplayedFunds(custody),
  };
}

/**
 * Which wallet this build is using, read from the vault alone.
 *
 * Like `walletStatus`, this deliberately does not start the worklet: the refusal has to be
 * decidable before any key material is opened, and on a build where the worklet cannot start
 * at all it still has to produce the right answer.
 */
export async function currentCustody(): Promise<Custody> {
  const storage = await loadSecureStorage(Platform.OS);
  if (!storage) return custodyOf({ keystoreWallet: false, devServerConfigured, splitPermitted });
  const record = await createWalletVault(storage).read();
  return custodyOf({ keystoreWallet: record !== null, devServerConfigured, splitPermitted });
}
