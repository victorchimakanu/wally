import fs from 'node:fs';
import path from 'node:path';
const directory = path.resolve('assets/wallyui');
/**
 * Single-colour icons drawn in a neutral take that role's colour from the palette in dark mode.
 * Anything multi-coloured, gradient-filled or in a brand colour is left exactly as exported.
 */
const NEUTRAL_TONES = { '#17201C': 'ink', '#333333': 'ink', '#72758A': 'muted', '#65736C': 'muted', '#68726D': 'muted' };
function toneOf(svg) {
  if (/Gradient|<image/.test(svg)) return null;
  const colours = new Set([...svg.matchAll(/(?:fill|stroke)="(#[0-9A-Fa-f]{3,8}|[a-zA-Z]+)"/g)].map(match => match[1].toUpperCase()).filter(value => value !== 'NONE'));
  return colours.size === 1 ? NEUTRAL_TONES[[...colours][0]] ?? null : null;
}
const entries = fs.readdirSync(directory).filter(name => name.endsWith('.svg')).map(name => {
  const svg = fs.readFileSync(path.join(directory, name), 'utf8');
  const root = svg.match(/<svg\b[^>]*>/)?.[0];
  const width = Number(root?.match(/\bwidth="([\d.]+)"/)?.[1]);
  const height = Number(root?.match(/\bheight="([\d.]+)"/)?.[1]);
  if (!width || !height) throw new Error(`Missing dimensions: ${name}`);
  const tone = toneOf(svg);
  return `  '${name}': { source: require('../../assets/wallyui/${name}'), width: ${width}, height: ${height}, tone: ${tone ? `'${tone}'` : 'null'} },`;
});
fs.writeFileSync('src/components/wally-assets.ts', [
  '/** Original Figma SVG dimensions, and the palette role a single-colour neutral icon takes in dark mode; regenerated by catalog-figma-assets.mjs. */',
  "export type AssetTone = 'ink' | 'muted' | null;",
  'export const vectorAssets = {',
  ...entries,
  '} as const satisfies Record<string, { source: number; width: number; height: number; tone: AssetTone }>;',
  '',
].join('\n'));
