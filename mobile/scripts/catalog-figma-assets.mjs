import fs from 'node:fs';
import path from 'node:path';
const directory = path.resolve('assets/wallyui');
const entries = fs.readdirSync(directory).filter(name => name.endsWith('.svg')).map(name => {
  const root = fs.readFileSync(path.join(directory, name), 'utf8').match(/<svg\b[^>]*>/)?.[0];
  const width = Number(root?.match(/\bwidth="([\d.]+)"/)?.[1]);
  const height = Number(root?.match(/\bheight="([\d.]+)"/)?.[1]);
  if (!width || !height) throw new Error(`Missing dimensions: ${name}`);
  return `  '${name}': { source: require('../../assets/wallyui/${name}'), width: ${width}, height: ${height} },`;
});
fs.writeFileSync('src/components/wally-assets.ts', '/** Original Figma SVG dimensions; regenerated by catalog-figma-assets.mjs. */\nexport const vectorAssets = {\n' + entries.join('\n') + '\n} as const;\n');
