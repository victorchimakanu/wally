/**
 * Collect the licence notices the app is obliged to carry.
 *
 * Apache-2.0 — which @tetherto/wdk and most of the WDK packages use — requires that a
 * distributed work carry the licence and any NOTICE file. MIT and BSD require the copyright
 * line and the permission notice. Shipping without them is a compliance problem on the day
 * the app is distributed, not a tidiness issue, which is why this is generated rather than
 * maintained by hand: a list someone has to remember to update is a list that goes stale.
 *
 * Production dependencies only. Build tools are not distributed and carry no obligation.
 *
 *   npm run notices          regenerate src/generated/notices.json
 *   npm run notices:check    fail if it is out of date (for CI, when there is CI)
 */
import { execFileSync } from "node:child_process";
import { readFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const MOBILE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
/**
 * A .ts module, not .json. Node's ESM loader demands an import attribute for JSON, Metro and
 * tsc each treat it differently, and a module sidesteps all three. The payload is a single
 * string literal parsed at load, so tsc does not have to infer a type for 742 objects.
 */
const OUT = path.join(MOBILE, "src/generated/notices.ts");

/** Files a package may ship its licence text in. */
const LICENCE_FILES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENCE.md", "license", "NOTICE", "NOTICE.txt"];

/** Every production dependency, flattened. `npm ls` is the authority on what actually ships. */
function productionTree() {
  const raw = execFileSync("npm", ["ls", "--omit=dev", "--all", "--json"], {
    cwd: MOBILE, encoding: "utf8", maxBuffer: 64 * 1024 * 1024,
  });
  const names = new Set();
  const walk = (node) => {
    for (const [name, child] of Object.entries(node.dependencies ?? {})) {
      names.add(name);
      walk(child);
    }
  };
  walk(JSON.parse(raw));
  return names;
}

function readPackage(name) {
  const dir = path.join(MOBILE, "node_modules", name);
  const manifest = path.join(dir, "package.json");
  if (!existsSync(manifest)) return null;
  let meta;
  try { meta = JSON.parse(readFileSync(manifest, "utf8")); } catch { return null; }

  const license = typeof meta.license === "string" ? meta.license
    : typeof meta.licenses?.[0]?.type === "string" ? meta.licenses[0].type
    : "UNKNOWN";

  let text = "";
  for (const file of LICENCE_FILES) {
    const candidate = path.join(dir, file);
    if (existsSync(candidate)) {
      try { text = readFileSync(candidate, "utf8").trim(); break; } catch { /* unreadable */ }
    }
  }

  return {
    name,
    version: meta.version ?? "",
    license,
    // The full text where a package ships one. Truncated hard: this is read on a phone and a
    // few packages ship enormous files, but the notice has to remain the notice.
    text: text.length > 12_000 ? `${text.slice(0, 12_000)}\n\n[truncated — full text at https://www.npmjs.com/package/${name}]` : text,
    homepage: typeof meta.homepage === "string" ? meta.homepage : "",
  };
}

const names = [...productionTree()].sort();
const packages = names.map(readPackage).filter(Boolean);

const missing = packages.filter((p) => p.license === "UNKNOWN");
const noText = packages.filter((p) => !p.text);

/**
 * Deduplicate the licence texts.
 *
 * Hundreds of packages ship a byte-identical MIT or Apache file, and storing each copy put
 * 2.7MB of JSON into the app bundle. That matters more here than most places: the audit
 * already flags download size as a real cost for users on metered mobile data.
 *
 * The deduplication is by exact text, so it is lossless — MIT requires each package's own
 * copyright line to be carried, and two packages with different copyright lines have
 * different text and are stored separately.
 */
const texts = [];
const indexOfText = new Map();
for (const pkg of packages) {
  if (!pkg.text) { pkg.textRef = -1; continue; }
  let at = indexOfText.get(pkg.text);
  if (at === undefined) { at = texts.length; texts.push(pkg.text); indexOfText.set(pkg.text, at); }
  pkg.textRef = at;
  delete pkg.text;
}

mkdirSync(path.dirname(OUT), { recursive: true });
const payload = {
  generated: "run `npm run notices` to regenerate — do not edit by hand",
  count: packages.length,
  /** Unique licence texts. A package's `textRef` indexes into this, or -1 for none. */
  texts,
  packages,
};
const next = `// Generated by \`npm run notices\`. Do not edit.
//
// Licence notices for every production dependency, as Apache-2.0 and the BSD/MIT family
// require a distributed work to carry. Texts are deduplicated by exact content, which is
// lossless: a package's own copyright line makes its text distinct.
export type NoticesData = {
  count: number;
  texts: string[];
  packages: { name: string; version: string; license: string; homepage: string; textRef: number }[];
};
const raw = ${JSON.stringify(JSON.stringify(payload))};
export default JSON.parse(raw) as NoticesData;
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== next) {
    console.error("notices are out of date. Run: npm run notices");
    process.exit(1);
  }
  console.log(`notices are current (${packages.length} packages)`);
  process.exit(0);
}

writeFileSync(OUT, next);
console.log(`wrote ${path.relative(MOBILE, OUT)} — ${packages.length} production packages`);
if (missing.length) console.warn(`  ${missing.length} with no declared licence: ${missing.slice(0, 5).map((p) => p.name).join(", ")}`);
if (noText.length) console.warn(`  ${noText.length} ship no licence file; the SPDX identifier is recorded instead`);
